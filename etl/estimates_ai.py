"""Precomputed "Street view" summary per company, stored in estimates/{T}.json under street_view.

Grounding: the model sees only records already stored in the bundle, each with a reference id
(C:<period> consensus, R:<period>:<days> revision, S:<quarter end> surprise, A:<benzinga id> analyst action,
T:targets, D:rating distribution, G:<guidance id> guidance vs consensus). Every point must cite refs; refs that
do not exist are removed, and a point whose numbers cannot be found in its cited records is kept but marked
unverified. Generated by the build cron, never on page load. Labeled AI-generated with model and date.
"""
import json
import os
import re
import time

from .common import now_iso, request

MODELS = [os.environ.get("FU_ESTIMATES_MODEL", "kimi-k3p1-pro"), os.environ.get("FU_ESTIMATES_FALLBACK", "deepseek-v4p1-flash")]
URL = "https://api.fireworks.ai/inference/v1/chat/completions"


def context(b, max_actions=25):
    """Reference table handed to the model: {ref: record}."""
    refs = {}
    c = b.get("consensus") or {}
    for p in c.get("periods") or []:
        refs[f"C:{p['code']}"] = {"period": p["label"], "fiscal_period_end": p["end"], "eps_consensus": p["eps"], "revenue_consensus": p["revenue"],
                                  "as_of": c.get("as_of"), "provider": "Yahoo Finance"}
    for code, row in (b.get("revisions") or {}).items():
        for w, r in row.items():
            if r:
                refs[f"R:{code}:{w}"] = {"period": code, "window_days": int(w), **r}
    for s in (b.get("surprises") or [])[-4:]:
        refs[f"S:{s['quarter_end']}"] = {k: s.get(k) for k in ("quarter_end", "eps_actual", "eps_estimate", "surprise_pct", "basis")} | {
            "gaap_eps_sec": (s.get("gaap_eps") or {}).get("v"), "next_session_move": (s.get("reaction") or {}).get("r1")}
    for a in (b.get("actions") or [])[:max_actions]:
        refs[f"A:{a['id']}"] = {k: a.get(k) for k in ("date", "firm", "analyst", "action", "action_pt", "rating_prior", "rating_current", "pt_prior", "pt_current")}
    t = (b.get("targets") or {}).get("stats")
    if t:
        refs["T"] = {**t, "price": (b.get("price") or {}).get("close"), "price_date": (b.get("price") or {}).get("date"), "window_from": b["targets"]["since"]}
    d = b.get("ratings") or {}
    if d.get("n"):
        refs["D"] = {"counts": d["counts"], "firms": d["n"], "window_from": d["since"]}
    for g in (b.get("guidance") or {}).get("vs_consensus") or []:
        if g.get("scale_check"):
            refs[f"G:{g['guide_id']}"] = {k: g.get(k) for k in ("label", "period", "guide_low", "guide_high", "guide_mid", "consensus", "issued", "position", "gap_pct")}
    return refs


PROMPT = """You are writing the "Street view" box on an equity research terminal for {name} ({tk}).
Use ONLY the records below. Each record has a reference id. Do not use outside knowledge, do not predict prices,
do not give investment advice. Write 3 to 5 short factual points about where sell-side analysts stand: consensus
level and recent revisions, rating and price-target distribution, notable recent rating or target changes, the
earnings surprise record, and how consensus compares with company guidance when a G record exists.
Every point must cite one or more reference ids from the records in "refs". Quote numbers as they appear
(you may round to 2 decimals or express ratios as percentages).
Return JSON: {{"headline": "<one sentence>", "points": [{{"text": "...", "refs": ["C:0q", "A:..."]}}]}}

Records:
{records}
"""


def number_tokens(text):
    return [t for t in re.findall(r"-?\d[\d,]*\.?\d*", text or "") if re.sub(r"\D", "", t)]


def values_in(obj, out=None):
    out = [] if out is None else out
    if isinstance(obj, dict):
        for v in obj.values():
            values_in(v, out)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            values_in(v, out)
    elif isinstance(obj, (int, float)) and not isinstance(obj, bool):
        out.append(float(obj))
    elif isinstance(obj, str):
        for t in number_tokens(obj):
            try:
                out.append(float(t.replace(",", "")))
            except ValueError:
                pass
    return out


def supported(tok, vals):
    """A number in the text is supported if some cited value matches it directly, as a percentage, or in
    thousands/millions/billions, within rounding of the printed precision."""
    try:
        x = abs(float(tok.replace(",", "")))
    except ValueError:
        return True
    if x in (7, 30, 60, 90, 365) or (1990 <= x <= 2100 and "." not in tok):   # revision windows, years
        return True
    dec = len(tok.split(".")[1]) if "." in tok else 0
    tol = 0.5 * 10 ** -dec + 1e-9
    for v in vals:
        a = abs(v)
        for scaled in (a, a * 100, a / 1e3, a / 1e6, a / 1e9, a / 1e12):
            if abs(scaled - x) <= max(tol, x * 0.005):
                return True
    return False


def validate(out, refs):
    points = []
    for p in (out or {}).get("points") or []:
        text = str(p.get("text") or "").strip()
        cited = [r for r in p.get("refs") or [] if r in refs]
        if not text or not cited:
            continue
        vals = values_in([refs[r] for r in cited])
        bad = [t for t in number_tokens(text) if not supported(t, vals)]
        points.append({"text": text, "refs": cited, "verified": not bad, "unsupported_numbers": bad or None})
    return points


def complete(prompt, key):
    last = None
    for model in MODELS:
        try:
            d = json.loads(request(URL, method="POST", data={"model": f"accounts/fireworks/models/{model}", "messages": [{"role": "user", "content": prompt}],
                                                             "max_tokens": 1800, "temperature": 0.2, "response_format": {"type": "json_object"}},
                                   headers={"Authorization": f"Bearer {key}"}, timeout=120, retries=2))
            txt = re.sub(r"(?s)<think>.*?</think>", "", d["choices"][0]["message"]["content"] or "").strip()
            m = re.search(r"(?s)\{.*\}", txt)
            return json.loads(m.group(0) if m else txt), model
        except Exception as e:
            last = e
    raise last


def street_view(b, key, completer=complete):
    refs = context(b)
    if len(refs) < 3:
        return None
    out, model = completer(PROMPT.format(name=b.get("name") or b["ticker"], tk=b["ticker"], records=json.dumps(refs, default=str)[:24000]), key)
    pts = validate(out, refs)
    if not pts:
        return None
    return {"label": "AI-generated", "generated_at": now_iso(), "model": model, "headline": str(out.get("headline") or "")[:240],
            "headline_verified": False, "points": pts, "refs": {r: refs[r] for p in pts for r in p["refs"]},
            "inputs_as_of": {"consensus": (b.get("consensus") or {}).get("as_of"), "actions_to": (b.get("coverage") or {}).get("actions_to")}}


def run(sb, state, dry=False, deadline=None, limit=None, tickers=None):
    """Regenerate summaries for bundles whose inputs changed since the last summary."""
    key = os.environ.get("FIREWORKS_API_KEY")
    if not key and not dry:
        return {"skipped": "FIREWORKS_API_KEY not set"}
    idx = (sb.get_json("estimates/index.json") or {}).get("companies") or []
    done, failed, todo = 0, {}, []
    for r in idx:
        if tickers and r["ticker"] not in tickers:
            continue
        sig = f"{r.get('consensus_as_of')}|{r.get('last_action')}|{r.get('n_actions')}"
        if state.setdefault("summaries", {}).get(r["ticker"]) != sig:
            todo.append((r["ticker"], sig))
    if dry:
        return {"todo": len(todo)}
    for tk, sig in todo[: limit or 60]:
        if deadline and time.time() > deadline:
            break
        try:
            b = sb.get_json(f"estimates/{tk}.json")
            sv = street_view(b, key)
            if sv:
                b["street_view"] = sv
                sb.put_json(f"estimates/{tk}.json", b, cache="max-age=600")
                done += 1
            state["summaries"][tk] = sig
        except Exception as e:
            failed[tk] = str(e)[:120]
    return {"todo": len(todo), "done": done, "failed": failed}
