def model_block():
    ends = M['ends']
    head = [dt.date.fromisoformat(e).strftime("%b '%y") for e in ends]
    R = M['rows']
    money = lambda v: '–' if v is None else f"{v / 1e9:,.2f}" if abs(v) < 1e10 else f"{v / 1e9:,.1f}"
    def row(label, key, cls=''):
        return {'label': label, 'cells': [money(v) for v in R[key]], 'series': [None if v is None else round(v / 1e9, 2) for v in R[key]], 'cls': cls}
    def ratio(label, num, den=None, kind='margin'):
        vals = []
        for i in range(len(ends)):
            a = R[num][i]
            if kind == 'yoy':
                b = R[num][i - 4] if i >= 4 else None
                vals.append(None if a is None or b is None else a / b - 1)
            else:
                b = R[den][i]
                vals.append(None if a is None or not b else a / b)
        return {'label': label, 'cls': 'pct', 'cells': ['' if v is None else (pct(v, 0) if kind == 'yoy' else f"{v * 100:.1f}%") for v in vals]}
    eps = {'label': 'EPS, diluted ($)', 'cls': 'tot', 'cells': ['–' if v is None else f"{v:.2f}" for v in R['EPS diluted']], 'series': R['EPS diluted']}
    fcf = [None if o is None or c is None else o - c for o, c in zip(R['Operating cash flow'], R['Capital expenditures'])]
    R['Free cash flow'] = fcf
    rows = [row('Revenue', 'Revenue', 'tot'), ratio('  YoY growth', 'Revenue', kind='yoy'), row('Cost of revenue', 'Cost of revenue'), row('Gross profit', 'Gross profit', 'tot'),
            ratio('  Gross margin', 'Gross profit', 'Revenue'), row('Research & development', 'Research & development'), row('SG&A', 'SG&A'),
            row('Operating income', 'Operating income', 'tot'), ratio('  Operating margin', 'Operating income', 'Revenue'), row('Net income', 'Net income', 'tot'),
            ratio('  Net margin', 'Net income', 'Revenue'), eps, row('Operating cash flow', 'Operating cash flow'), row('Capital expenditures', 'Capital expenditures'),
            row('Free cash flow', 'Free cash flow', 'tot'), ratio('  FCF margin', 'Free cash flow', 'Revenue')]
    return {'t': 'model', 'head': head, 'rows': rows}


