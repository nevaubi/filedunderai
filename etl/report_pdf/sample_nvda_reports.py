def render(name, tpl, footer, meta, **ctx):
    html = env.from_string(tpl).render(css=(P / 'report.css').read_text(), charts=(P / 'charts2.js').read_text(), data_json=json.dumps(D), meta=meta, **ctx)
    (P / f'{name}.html').write_text(html)
    subprocess.run(['node', str(P / 'pdf.js'), str(P / f'{name}.html'), str(P / f'{name}.pdf'), 'footer' if footer else 'none', meta['title']], check=True)
    return P / f'{name}.pdf'


